def export(src_dir, page, slug):
    path = os.path.join(SRC, src_dir, page + ".png")
    im = Image.open(path).convert("L")
    if im.width > MAXW:
        im = im.resize((MAXW, int(im.height * MAXW / im.width)), Image.LANCZOS)
    im = im.point(lambda v: min(255, (v // 16) * 16 + 8))
    fn = f"E85_{slug}.png"
    im.save(os.path.join(IMG, fn), optimize=True)
    return fn, os.path.getsize(os.path.join(IMG, fn))

def main():
    for title, (intro, related, sections) in ARTICLES.items():
        if len(sys.argv) > 1 and not any(a in title for a in sys.argv[1:]):
            continue
        lines = [f"'''{title}''' — {intro} Изображения листов получены со скана.", ""]
        total = 0
        for sec, items in sections:
            lines.append(f"== {sec} ==")
            lines.append("")
            for src_dir, page, slug, cap in items:
                fn, size = export(src_dir, page, slug)
                total += size
                lines.append(f"[[Файл:{fn}|thumb|center|1000px|{cap}]]")
                lines.append("")
        lines.append("== См. также ==")
        lines.append("")
        for r in related:
            lines.append(f"* [[{r}]]")
        lines.append("")
        lines.append(CAT)
        with open(os.path.join(OUT, title + ".wiki"), "w", encoding="utf-8", newline="\n") as f:
            f.write("\n".join(lines) + "\n")
        print(title, f"{total/1e6:.1f} MB")

if __name__ == "__main__":
    main()
