"""
Общая палитра инструментов ЯЗС. Разряды регистра тонового канала:
D0 ВЧ, D1 СЧ, D2 НЧ (полосы), D3 +12 дБ, D4 удар (быстрая атака, спад
~0.5 с), D5 удержание (с одним D5 - плавная атака ~0.3 с).

Уровни по замеру (measure.py, канал 1, C3-C5, дБ от полной шкалы):
НЧ+СЧ с D3 и D4+D5 -12..-13, НЧ -13..-16, СЧ -18..-21, ВЧ -21..-27;
без D3 на 8-10 дБ тише; D5 без D4 на ~4 дБ тише D4+D5; удар D4 за 300 мс
спадает на 15 дБ.

Ударный 6 (D0-D2 высота, D3 громче и дольше): $08 бочка ~76 Гц, $09/$0A
низкий том ~145 Гц, $0B/$0C средний ~220 Гц, $0D высокий ~300 Гц с шумом,
$0E/$0F ~300-380 Гц, больше середины. Ударный 7: шум 7-11 кГц, спад 0.4 с:
$08/$09 ~7 кГц, $0A ~8 кГц, $0B ~11 кГц (без D3 тише и короче).
"""

HF, MF, LF, LOUD, HIT, HOLD = 0x01, 0x02, 0x04, 0x08, 0x10, 0x20

# Ударные: буква -> пресет (D0-D3)
KIT6 = {"k": 0x08, "K": 0x00, "t": 0x09, "u": 0x0B, "v": 0x0D, "w": 0x0F,
        "s": 0x0E, "S": 0x06, "p": 0x05}
KIT7 = {"h": 0x03, "H": 0x0B, "o": 0x0A, "c": 0x08, "x": 0x00, "z": 0x02}


def add_standard(song):
    """Палитра, общая для частей; каждая часть добавляет свои"""
    i = song.instrument
    # Орган: удар с удержанием на всех полосах
    i("organ", "ОРГАН", [HOLD | HIT | LOUD | LF | MF | HF], meter=(15, 12, 2))
    i("organ_soft", "ФЛЕЙТ.Р", [HOLD | HIT | LF | MF], meter=(10, 8, 2))
    i("pedal", "ПЕДАЛЬ", [HOLD | HIT | LOUD | LF], meter=(14, 11, 2))
    # Струнные: плавная атака, легкое вибрато после задержки
    i("strings", "СТРУННЫЕ", [HOLD | LOUD | LF | MF], vib=(18, 4, 2), meter=(13, 12, 1))
    i("strings_hi", "СКРИПКИ", [HOLD | LOUD | MF | HF], vib=(14, 5, 2), meter=(12, 11, 1))
    # Щипковые: удар без удержания
    i("pluck", "АРФА", [HIT | LOUD | LF | MF], meter=(14, 0, 10))
    i("piano", "ФОРТЕПЬ.", [HIT | LOUD | LF | MF | HF], meter=(15, 0, 8))
    i("bass", "БАС", [HIT | LOUD | LF], meter=(15, 0, 6))
    i("bass_hold", "БАС", [HOLD | HIT | LOUD | LF], meter=(15, 10, 3))
    # Духовые
    i("flute", "ФЛЕЙТА", [HOLD | LOUD | MF | HF], vib=(16, 5, 2), meter=(12, 11, 1))
    i("brass", "МЕДЬ", [HOLD | HIT | LOUD | LF | MF | HF], vib=(20, 4, 1), meter=(15, 13, 2))
    i("lead", "СОЛО", [HOLD | HIT | LOUD | MF | HF], vib=(12, 5, 3), meter=(15, 13, 2))
