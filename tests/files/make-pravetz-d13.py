# Диск DOS 3.2 (13 секторов, .d13) для disk-pravetz-82-13sector: на нем
# только загрузочный сектор - программа, которая печатает строку и стоит.
# Загрузчик P5 на 13 секторов (Apple 341-0009) кладет сектор 0 в $0300-$03FF
# не подряд, а в порядке 5&3 (это собирает уже код DOS 3.2), и переходит на
# $0301. Порядок ниже снят с машины: байт $0300+k - байт MAP[k] сектора;
# последний байт сектора в $03FF доходит не целиком.
#
#   python make-pravetz-d13.py  ->  pravetz-13sector.d13
